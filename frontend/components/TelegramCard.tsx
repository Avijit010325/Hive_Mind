"use client";

import { useEffect, useState } from "react";
import { api, errorText, type LinkOffer, type TelegramState } from "@/lib/api";

/** Connect / disconnect Telegram. While a link is on offer it polls until the chat appears. */
export default function TelegramCard() {
  const [state, setState] = useState<TelegramState | null>(null);
  const [offer, setOffer] = useState<(LinkOffer & { before: number; started: number }) | null>(null);
  const [error, setError] = useState("");
  const [busy, setBusy] = useState(false);

  const load = () => api<TelegramState>("GET", "/api/telegram").then((next) => { setState(next); return next; });
  useEffect(() => { load().catch((err) => setError(errorText(err))); }, []);

  useEffect(() => {
    if (!offer) return;
    const timer = setInterval(async () => {
      const next = await load().catch(() => null);
      if (!next) return;
      if (next.links.length > offer.before || Date.now() - offer.started > offer.minutes * 60_000) setOffer(null);
    }, 2500);
    return () => clearInterval(timer);
  }, [offer]);

  async function connect() {
    setBusy(true);
    setError("");
    try {
      const before = (await load()).links.length;
      const link = await api<LinkOffer>("POST", "/api/telegram/link");
      setOffer({ ...link, before, started: Date.now() });
    } catch (err) {
      setError(errorText(err));
    }
    setBusy(false);
  }

  async function unlink(id: number) {
    if (!confirm("Disconnect this Telegram chat?")) return;
    await api("DELETE", `/api/telegram/links/${id}`).catch(() => {});
    load().catch(() => {});
  }

  let body: React.ReactNode = null;
  if (!state) {
    body = error ? <p className="error">{error}</p> : <p className="muted small">Loading…</p>;
  } else if (!state.configured || !state.bot) {
    body = (
      <p className="muted small">
        {state.configured
          ? "The Telegram bot token on this server isn't working. Check TELEGRAM_BOT_TOKEN."
          : "Telegram isn't set up on this server yet. The admin needs to add TELEGRAM_BOT_TOKEN to .env."}
      </p>
    );
  } else {
    const linked = state.links.length > 0;
    body = (
      <div className="stack">
        {linked ? (
          <>
            <p className="small">✅ Connected. Open the chat and just start typing.</p>
            <ul className="list">
              {state.links.map((link) => (
                <li key={link.id}>
                  <span>{link.display || "Telegram chat"}</span>
                  <button title="Disconnect" aria-label="Disconnect this chat" onClick={() => unlink(link.id)}>✕</button>
                </li>
              ))}
            </ul>
            <a className="btn dark full" href={`https://t.me/${state.bot}`} target="_blank" rel="noopener">Open @{state.bot}</a>
          </>
        ) : (
          !offer && <p className="muted small">Talk to your whole crew from one Telegram chat. One tap, no setup.</p>
        )}
        {offer ? (
          <>
            <a className="btn accent full" href={offer.url} target="_blank" rel="noopener">Open Telegram and press Start</a>
            <p className="muted small">On a computer? Scan this with your phone:</p>
            {/* SVG generated by our own API */}
            <div className="qr" dangerouslySetInnerHTML={{ __html: offer.qr }} />
            <p className="muted small waiting">
              <span className="spinner" />Waiting for you to press Start. The link is valid for {offer.minutes} minutes.
            </p>
          </>
        ) : (
          <button className={`btn full ${linked ? "ghost" : "accent"}`} disabled={busy} onClick={connect}>
            {linked ? "Connect another chat" : "Connect Telegram"}
          </button>
        )}
        {error && <p className="error">{error}</p>}
      </div>
    );
  }

  return (
    <div className="card">
      <h3>Telegram</h3>
      {body}
    </div>
  );
}
